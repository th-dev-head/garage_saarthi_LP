// Helper function to get location data by slug (supporting aliases)
export function getLocationBySlug(slug) {
  if (!slug) return null;
  const normalizedSlug = slug.toLowerCase().replace(/^\/|\/$/g, "");
  
  // Direct match
  if (LOCATIONS_DATA[normalizedSlug]) {
    return LOCATIONS_DATA[normalizedSlug];
  }
  
  // Alias match
  for (const key of Object.keys(LOCATIONS_DATA)) {
    const loc = LOCATIONS_DATA[key];
    if (loc.aliasSlugs && loc.aliasSlugs.includes(normalizedSlug)) {
      return loc;
    }
  }
  
  return null;
}

// List of all primary location slugs + alias slugs for static params
export function getAllLocationSlugs() {
  const slugs = [];
  for (const key of Object.keys(LOCATIONS_DATA)) {
    slugs.push(key);
    const loc = LOCATIONS_DATA[key];
    if (loc.aliasSlugs) {
      slugs.push(...loc.aliasSlugs);
    }
  }
  return slugs;
}

